# --- Accented letters (composed) -------------------------------------------------------
ACCENTS = {
    "acute": [".#", "#."],
    "grave": ["#.", ".#"],
    "circ": [".#.", "#.#"],
    "uml": ["#.#"],
}
COMPOSED = {
    "à": ("a", "grave"), "â": ("a", "circ"), "ä": ("a", "uml"),
    "é": ("e", "acute"), "è": ("e", "grave"), "ê": ("e", "circ"), "ë": ("e", "uml"),
    "î": ("ı", "circ"), "ï": ("ı", "uml"), "ô": ("o", "circ"), "ö": ("o", "uml"),
    "ù": ("u", "grave"), "û": ("u", "circ"), "ü": ("u", "uml"), "ÿ": ("y", "uml"),
    "À": ("A", "grave"), "Â": ("A", "circ"), "Ä": ("A", "uml"),
    "É": ("E", "acute"), "È": ("E", "grave"), "Ê": ("E", "circ"), "Ë": ("E", "uml"),
    "Î": ("I", "circ"), "Ï": ("I", "uml"), "Ô": ("O", "circ"), "Ö": ("O", "uml"),
    "Ù": ("U", "grave"), "Û": ("U", "circ"), "Ü": ("U", "uml"), "Ÿ": ("Y", "uml"),
}


def pixels(c):
    """Set of pixels (x, y) of a character and its width."""
    rows, bottom = G[c]
    w = max(len(r) for r in rows)
    px = set()
    for i, r in enumerate(rows):
        y = bottom + len(rows) - 1 - i
        for x, ch in enumerate(r):
            if ch == "#":
                px.add((x, y))
    return px, w


def compose(base, accent):
    bpx, bw = pixels(base)
    arows = ACCENTS[accent]
    aw = len(arows[0])
    w = max(bw, aw)
    bx, ax = (w - bw) // 2, (w - aw) // 2 + (1 if accent == "acute" and w > aw else 0)
    top = max(y for _, y in bpx)
    # One blank row between the letter and the accent; the diaeresis sits on the bottom row.
    y0 = top + 2
    px = {(x + bx, y) for x, y in bpx}
    for i, r in enumerate(reversed(arows)):
        for x, ch in enumerate(r):
            if ch == "#":
                px.add((x + ax, y0 + i))
    return px, w


def cedilla(base):
    px, w = pixels(base)
    cx = w // 2
    px |= {(cx, -1), (cx - 1, -2)}
    return px, w


def draw(px):
    pen = TTGlyphPen(None)
    # One rectangle per horizontal run of pixels (clockwise, as TrueType requires).
    rows = {}
    for x, y in px:
        rows.setdefault(y, []).append(x)
    for y, xs in rows.items():
        xs.sort()
        start = prev = xs[0]
        for x in xs[1:] + [None]:
            if x is not None and x == prev + 1:
                prev = x
                continue
            x0, x1, y0, y1 = start * UNIT, (prev + 1) * UNIT, y * UNIT, (y + 1) * UNIT
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
            if x is not None:
                start = prev = x
    return pen.glyph()


def main():
    shapes = {c: pixels(c) for c in G}
    for c, (base, acc) in COMPOSED.items():
        shapes[c] = compose(base, acc)
    shapes["ç"] = cedilla("c")
    shapes["Ç"] = cedilla("C")

    names = [".notdef", "space", "nbspace"]
    cmap = {0x20: "space", 0xA0: "nbspace", 0x202F: "nbspace"}
    glyphs = {".notdef": draw({(x, y) for x in range(5) for y in range(7) if x in (0, 4) or y in (0, 6)}),
              "space": TTGlyphPen(None).glyph(), "nbspace": TTGlyphPen(None).glyph()}
    metrics = {".notdef": (6 * UNIT, 0), "space": (4 * UNIT, 0), "nbspace": (3 * UNIT, 0)}
    for c, (px, w) in sorted(shapes.items()):
        name = f"uni{ord(c):04X}"
        names.append(name)
        cmap[ord(c)] = name
        glyphs[name] = draw(px)
        metrics[name] = ((w + 1) * UNIT, min(x for x, _ in px) * UNIT)

    fb = FontBuilder(EM * UNIT, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    asc, desc = 10 * UNIT, -2 * UNIT
    fb.setupHorizontalHeader(ascent=asc, descent=desc, lineGap=0)
    fb.setupNameTable({"familyName": "PSX Souls", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=asc, sTypoDescender=desc, sTypoLineGap=0, usWinAscent=asc, usWinDescent=-desc,
                sxHeight=5 * UNIT, sCapHeight=7 * UNIT, fsSelection=0x40)
    fb.setupPost()
    fb.save(OUT)
    print(f"{len(shapes)} glyphs -> {os.path.normpath(OUT)}")


main()
